"""Generate the waterproof arm's TANK IK model for Dream-1, with provenance. Offline.

Why: in the aquarium the arm works toward its base -x (shoulder_pan reads about
+182..186 deg), and Dream assumes base +x is forward. An arm file has no field
that turns the base, and the URDF's pan limits (-185.4..127.6 deg) are from an
older J1 frame. So this writes a URDF variant:

- a new root link `dream_base`, turned 180 deg about z above `base_link`
  (fixed joint `dream_base_to_base_link`, rpy 0 0 pi), so Dream's +x is down
  the tank and `base_link` keeps its physical meaning;
- `shoulder_pan`'s origin turned 180 deg as well, so the two turns cancel in
  the chain and IK pan = motor pan - 180 deg (+182..191 becomes +2..11);
- the six arm joints' limits from the unit's own follower profile
  (`configs/viscous/viscous_waterproof_01/evidence/lab-hardware-profile.json`),
  mapped through `configs/viscous/model/motor_to_urdf.json` (J5 sign -1; J5/J6
  hand-tested 2026-11-08), and pan narrowed to +-90 deg about Dream's forward by default.

Outputs (scripts/viscous-dream1/real/tank_model/): the URDF, a provenance
sidecar whose `approval.status` is "pending_gavin_approval" until Gavin edits
it, and a DRY-RUN arm file (no tcp_calibration; its tcp is copied unchanged
from viscous_arm.json, never confirmed). `--export DIR` also writes the URDF
plus a copy of the meshes into DIR for Gavin to load in `dreamcli tcp`.

Run: .venv/bin/python scripts/viscous-dream1/real/make_tank_arm.py [--export ~/viscous-dream-real/tank_model]
"""

from __future__ import annotations

import argparse
import json
import math
import shutil
import sys
import time
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import dream_real_core as core  # noqa: E402

SRC_URDF = core.ROOT / "configs/viscous/model/viscous_arm.urdf"
PROFILE = core.ROOT / "configs/viscous/viscous_waterproof_01/evidence/lab-hardware-profile.json"
SIM_ARM = core.ROOT / "scripts/viscous-dream1/viscous_arm.json"
OUT = core.HERE / "tank_model"
NAME = "viscous_waterproof_tank"
ROOT_LINK, ROOT_JOINT = "dream_base", "dream_base_to_base_link"


def build_urdf(source: bytes, ik_limits_deg: dict) -> bytes:
    root = ET.fromstring(source)
    joints = {j.get("name"): j for j in root.findall("joint")}
    pan = joints["shoulder_pan"]
    origin = pan.find("origin")
    if origin.get("parent") or pan.find("parent").get("link") != "base_link":
        raise ValueError("shoulder_pan must hang from base_link")
    if [float(v) for v in origin.get("rpy", "0 0 0").split()] != [0.0, 0.0, 0.0]:
        raise ValueError("expected shoulder_pan origin rpy 0 0 0 in the source URDF")
    origin.set("rpy", f"0 0 {math.pi!r}")
    for name, (lo, hi) in ik_limits_deg.items():
        limit = joints[name].find("limit")
        limit.set("lower", f"{math.radians(lo):.9f}")
        limit.set("upper", f"{math.radians(hi):.9f}")
    link = ET.Element("link", name=ROOT_LINK)
    joint = ET.Element("joint", name=ROOT_JOINT, type="fixed")
    ET.SubElement(joint, "parent", link=ROOT_LINK)
    ET.SubElement(joint, "child", link="base_link")
    ET.SubElement(joint, "origin", xyz="0 0 0", rpy=f"0 0 {math.pi!r}")
    root.insert(0, joint)
    root.insert(0, link)
    root.insert(
        0,
        ET.Comment(
            f" Tank IK variant of viscous_arm.urdf, generated by scripts/viscous-dream1/real/make_tank_arm.py. "
            f"dream_base is base_link turned 180 deg about z; IK shoulder_pan = motor - 180 deg. "
            f"PENDING GAVIN'S APPROVAL: see {NAME}.provenance.json "
        ),
    )
    ET.indent(root, "  ")
    return ET.tostring(root, encoding="utf-8", xml_declaration=True) + b"\n"


def frame_check(
    source: bytes, variant: bytes, jmap: core.JointMap, motor_limits: dict, n: int = 200
) -> float:
    """Max error (m) between the variant's tool in dream_base and Rz(pi) x the original's tool in base_link."""
    a, b = core.parse_urdf(source), core.parse_urdf(variant)
    rz = np.diag([-1.0, -1.0, 1.0])
    rng = np.random.default_rng(20261107)
    worst = 0.0
    for _ in range(n):
        motor = {m: rng.uniform(*motor_limits[m]) for m in core.ARM}
        urdf = {m: math.radians(v) for m, v in jmap.urdf_deg(motor).items()}
        ik = dict(zip(core.ARM, jmap.to_ik(motor), strict=True))
        ta = core.fk(a, "base_link", "tool0", urdf)
        tb = core.fk(b, ROOT_LINK, "tool0", ik)
        worst = max(
            worst,
            float(np.abs(rz @ ta[:3, 3] - tb[:3, 3]).max()),
            float(np.abs(rz @ ta[:3, :3] - tb[:3, :3]).max()),
        )
    return worst


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument(
        "--pan-window-deg",
        type=float,
        default=90.0,
        help="keep IK pan within +-this of Dream's forward (motor 180); 0 = profile limits only",
    )
    p.add_argument(
        "--rest-motor-deg",
        type=json.loads,
        help='IK rest as motor degrees, e.g. {"shoulder_pan":184,...}; default: the sim arm file rest',
    )
    p.add_argument(
        "--export", type=Path, help="also write URDF + meshes here, for dreamcli tcp's Choose folder"
    )
    args = p.parse_args()

    source = SRC_URDF.read_bytes()
    profile = json.loads(PROFILE.read_text())["follower"]["joint_limits"]
    motor_limits = {m: tuple(profile[m]) for m in core.MOTORS}
    jmap = core.JointMap.load()
    ik_limits = jmap.ik_limits_deg(motor_limits)
    if args.pan_window_deg:
        lo, hi = ik_limits["shoulder_pan"]
        ik_limits["shoulder_pan"] = (max(lo, -args.pan_window_deg), min(hi, args.pan_window_deg))
    variant = build_urdf(source, ik_limits)
    error = frame_check(source, variant, jmap, motor_limits)
    if error > 1e-9:
        raise SystemExit(f"frame check failed: {error:.3e}")

    sim_arm = json.loads(SIM_ARM.read_text())
    if args.rest_motor_deg:
        rest = jmap.to_ik({m: float(args.rest_motor_deg[m]) for m in core.ARM})
        rest_source = f"--rest-motor-deg {json.dumps(args.rest_motor_deg, sort_keys=True)}"
    else:
        rest = list(sim_arm["rest"])
        rest_source = (
            "PLACEHOLDER: scripts/viscous-dream1/viscous_arm.json rest (Dream's sim work pose, in IK "
            "numbers = motor pan 180). docs/dream1-tank.md says Dream's folded rest fails the tank box; "
            "regenerate with --rest-motor-deg set to the hand-placed tank start pose."
        )
    for m, value in zip(core.ARM, rest, strict=True):
        lo, hi = ik_limits[m]
        if not lo <= math.degrees(value) <= hi:
            raise SystemExit(f"rest {m} {math.degrees(value):.1f} deg outside IK limits {lo:.1f}..{hi:.1f}")

    OUT.mkdir(parents=True, exist_ok=True)
    urdf_path = OUT / f"{NAME}.urdf"
    urdf_path.write_bytes(variant)
    arm = {
        "urdf": urdf_path.name,
        "base": ROOT_LINK,
        "flange": sim_arm["flange"],
        "tcp": sim_arm["tcp"],
        "approach": sim_arm["approach"],
        "jaw": sim_arm["jaw"],
        "rest": [round(v, 6) for v in rest],
    }
    (OUT / f"{NAME}_arm.json").write_text(json.dumps(arm, indent=1) + "\n")
    provenance = {
        "_copyright": "Copyright 2026 MakerMods. All rights reserved. Apache-2.0.",
        "what": "Tank IK model of the waterproof Viscous arm (viscous_waterproof_01) for Dream-1's client IK.",
        "generated_by": "scripts/viscous-dream1/real/make_tank_arm.py",
        "generated_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "approval": {
            "status": "pending_gavin_approval",
            "by": None,
            "at": None,
            "urdf_sha256_normalized": None,
            "how": (
                "Gavin reviews this file and the URDF, then sets status 'approved', by, at, and "
                f"urdf_sha256_normalized = {core.normalized_urdf_sha256(variant)} (the URDF's sha256 ignoring "
                "trailing newlines). dream_real.py refuses --live until then. Then run dreamcli tcp on the "
                "exported folder (README, order of operations)."
            ),
        },
        "urdf": {
            "file": urdf_path.name,
            "sha256": core.sha256_bytes(variant),
            "sha256_normalized": core.normalized_urdf_sha256(variant),
        },
        "sources": {
            "urdf": {"path": str(SRC_URDF.relative_to(core.ROOT)), "sha256": core.sha256_bytes(source)},
            "joint_limits_motor_deg": {
                "path": str(PROFILE.relative_to(core.ROOT)),
                "sha256": core.sha256_bytes(PROFILE.read_bytes()),
                "value": profile,
            },
            "motor_to_urdf": {
                "path": str(core.MOTOR_TO_URDF.relative_to(core.ROOT)),
                "sha256": core.sha256_bytes(core.MOTOR_TO_URDF.read_bytes()),
                "status": jmap.status,
            },
            "tool_keys": {
                "path": str(SIM_ARM.relative_to(core.ROOT)),
                "note": "tcp/approach/jaw copied unchanged into the dry-run arm file only. Never "
                "confirmed with dreamcli tcp; the live arm file comes from dreamcli tcp.",
            },
        },
        "changes": {
            "root": f"new link {ROOT_LINK}; fixed joint {ROOT_JOINT} {ROOT_LINK}->base_link rpy 0 0 pi",
            "shoulder_pan_origin": "rpy 0 0 0 -> 0 0 pi (cancels the root turn in the chain)",
            "ik_shoulder_pan": "IK = motor - 180 deg; one unwrapped branch, never wrapped",
            "joint_limits_ik_deg": {m: [round(lo, 4), round(hi, 4)] for m, (lo, hi) in ik_limits.items()},
            "pan_window_deg": args.pan_window_deg,
            "rest_ik_rad": arm["rest"],
            "rest_source": rest_source,
        },
        "checks": {
            "frame_check_max_error": error,
            "frame_check": "tool0 in dream_base == Rz(pi) * tool0 in base_link, 200 random profile poses",
        },
        "unverified": {
            **{
                m: f"sign {jmap.sign[m]:+.0f}: {jmap.status[m]} (motor_to_urdf.json)"
                for m in jmap.unverified()
            },
            "j1_frame": "J1 zero / limits after the 2026-11-05 re-zero work and the 2026-11-07 tank offset 185.8; "
            "the profile's +187.53 upper pan limit may be stale (docs/dream1-tank.md question 7)",
        },
    }
    core.atomic_json(OUT / f"{NAME}.provenance.json", provenance)
    print(
        f"wrote {urdf_path}, {NAME}_arm.json, {NAME}.provenance.json (approval pending); frame error {error:.1e}"
    )
    for m, (lo, hi) in ik_limits.items():
        print(f"  {m:14s} IK {lo:8.2f} .. {hi:8.2f} deg")
    if args.export:
        dest = args.export.expanduser()
        dest.mkdir(parents=True, exist_ok=True)
        (dest / urdf_path.name).write_bytes(variant)
        shutil.copytree(SRC_URDF.parent / "meshes", dest / "meshes", dirs_exist_ok=True)
        core.atomic_json(dest / f"{NAME}.provenance.json", provenance)
        print(f"exported {dest} (URDF + meshes) for dreamcli tcp")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
